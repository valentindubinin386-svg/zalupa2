class MainActivity : ComponentActivity() {

    private val requiredPermissions = arrayOf(
        Manifest.permission.CAMERA,
        Manifest.permission.ACCESS_FINE_LOCATION,
        Manifest.permission.ACCESS_COARSE_LOCATION
    )

    private val permissionLauncher = registerForActivityResult(
        ActivityResultContracts.RequestMultiplePermissions()
    ) { }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        Configuration.getInstance().load(this, getPreferences(Context.MODE_PRIVATE))

        if (!hasPermissions()) {
            permissionLauncher.launch(requiredPermissions)
        }

        setContent {
            MaterialTheme {
                MainAppScreen()
            }
        }
    }

    private fun hasPermissions(): Boolean {
        return requiredPermissions.all {
            ContextCompat.checkSelfPermission(this, it) == PackageManager.PERMISSION_GRANTED
        }
    }
}

enum class ScreenState {
    CAMERA,
    PREVIEW,
    MAP_PICKER
}

@Composable
fun MainAppScreen() {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()

    var screenState by remember { mutableStateOf(ScreenState.CAMERA) }
    var currentBitmap by remember { mutableStateOf<Bitmap?>(null) }
    var latitude by remember { mutableStateOf(59.9343) } // По умолчанию (СПб)
    var longitude by remember { mutableStateOf(30.3351) }
    var serverUrl by remember { mutableStateOf("https://example.com/api/upload") }
    var isSending by remember { mutableStateOf(false) }

    // Получаем реальную GPS-точку устройства при старте
    LaunchedEffect(Unit) {
        val fusedLocationClient = LocationServices.getFusedLocationProviderClient(context)
        try {
            fusedLocationClient.lastLocation.addOnSuccessListener { loc ->
                if (loc != null) {
                    latitude = loc.latitude
                    longitude = loc.longitude
                }
            }
        } catch (_: SecurityException) { }
    }

    when (screenState) {
        ScreenState.CAMERA -> {
            CameraView(
                onPhotoCaptured = { bitmap ->
                    currentBitmap = bitmap
                    screenState = ScreenState.PREVIEW
                }
            )
        }

        ScreenState.PREVIEW -> {
            currentBitmap?.let { bmp ->
                PreviewAndEditScreen(
                    bitmap = bmp,
                    lat = latitude,
                    lon = longitude,
                    serverUrl = serverUrl,
                    isSending = isSending,
                    onServerUrlChange = { serverUrl = it },
                    onRotate = {
                        val matrix = Matrix().apply { postRotate(90f) }
                        currentBitmap = Bitmap.createBitmap(bmp, 0, 0, bmp.width, bmp.height, matrix, true)
                    },
                    onOpenMap = { screenState = ScreenState.MAP_PICKER },
                    onRetake = {
                        currentBitmap = null
                        screenState = ScreenState.CAMERA
                    },
                    onSend = {
                        scope.launch {
                            isSending = true
                            val success = sendDataToServer(context, bmp, latitude, longitude, serverUrl)
                            isSending = false
                            if (success) {
                                Toast.makeText(context, "Успешно отправлено!", Toast.LENGTH_LONG).show()
                                currentBitmap = null
                                screenState = ScreenState.CAMERA
                            } else {
                                Toast.makeText(context, "Ошибка отправки", Toast.LENGTH_LONG).show()
                            }
                        }
                    }
                )
            }
        }

        ScreenState.MAP_PICKER -> {
            MapPickerScreen(
                initialLat = latitude,
                initialLon = longitude,
                onConfirm = { newLat, newLon ->
                    latitude = newLat
                    longitude = newLon
                    screenState = ScreenState.PREVIEW
                },
                onCancel = { screenState = ScreenState.PREVIEW }
            )
        }
    }
}

