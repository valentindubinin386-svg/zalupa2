package com.cleancam.app

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.graphics.Matrix
import androidx.exifinterface.media.ExifInterface
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaTypeOrNull
import okhttp3.MultipartBody
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.asRequestBody
import java.io.ByteArrayOutputStream
import java.io.File
import java.io.FileOutputStream
import java.util.concurrent.TimeUnit

object ImageProcessor {

    /**
     * Загружает фото, поворачивает по ориентации, масштабирует (макс 1920px),
     * сжимает в JPEG и сохраняет в новый файл без каких-либо EXIF-тегов.
     */
    suspend fun compressAndStripExif(sourceFile: File, outputFile: File, maxDimension: Int = 1920, quality: Int = 85): Boolean {
        return withContext(Dispatchers.IO) {
            try {
                val exif = ExifInterface(sourceFile.absolutePath)
                val orientation = exif.getAttributeInt(
                    ExifInterface.TAG_ORIENTATION,
                    ExifInterface.ORIENTATION_NORMAL
                )

                val options = BitmapFactory.Options().apply {
                    inJustDecodeBounds = true
                }
                BitmapFactory.decodeFile(sourceFile.absolutePath, options)

                var sampleSize = 1
                while (options.outWidth / sampleSize > maxDimension * 1.5 ||
                    options.outHeight / sampleSize > maxDimension * 1.5) {
                    sampleSize *= 2
                }

                val decodeOptions = BitmapFactory.Options().apply {
                    inSampleSize = sampleSize
                }
                val originalBitmap = BitmapFactory.decodeFile(sourceFile.absolutePath, decodeOptions) ?: return@withContext false

                val matrix = Matrix()
                when (orientation) {
                    ExifInterface.ORIENTATION_ROTATE_90 -> matrix.postRotate(90f)
                    ExifInterface.ORIENTATION_ROTATE_180 -> matrix.postRotate(180f)
                    ExifInterface.ORIENTATION_ROTATE_270 -> matrix.postRotate(270f)
                }

                val rotatedBitmap = Bitmap.createBitmap(
                    originalBitmap, 0, 0,
                    originalBitmap.width, originalBitmap.height,
                    matrix, true
                )

                val width = rotatedBitmap.width
                val height = rotatedBitmap.height
                val scale = if (width > height) {
                    maxDimension.toFloat() / width
                } else {
                    maxDimension.toFloat() / height
                }

                val scaledBitmap = if (scale < 1.0f) {
                    Bitmap.createScaledBitmap(
                        rotatedBitmap,
                        (width * scale).toInt(),
                        (height * scale).toInt(),
                        true
                    )
                } else {
                    rotatedBitmap
                }

                val outStream = FileOutputStream(outputFile)
                scaledBitmap.compress(Bitmap.CompressFormat.JPEG, quality, outStream)
                outStream.flush()
                outStream.close()
                true
            } catch (e: Exception) {
                e.printStackTrace()
                false
            }
        }
    }

    /**
     * Отправка чистого файла и координат на указанный URL сервера
     */
    suspend fun uploadToServer(
        serverUrl: String,
        file: File,
        latitude: Double,
        longitude: Double,
        comment: String
    ): Result<String> {
        return withContext(Dispatchers.IO) {
            try {
                val client = OkHttpClient.Builder()
                    .connectTimeout(30, TimeUnit.SECONDS)
                    .writeTimeout(60, TimeUnit.SECONDS)
                    .readTimeout(30, TimeUnit.SECONDS)
                    .build()

                val requestBody = MultipartBody.Builder()
                    .setType(MultipartBody.FORM)
                    .addFormDataPart("latitude", latitude.toString())
                    .addFormDataPart("longitude", longitude.toString())
                    .addFormDataPart("comment", comment)
                    .addFormDataPart(
                        "photo",
                        file.name,
                        file.asRequestBody("image/jpeg".toMediaTypeOrNull())
                    )
                    .build()

                val request = Request.Builder()
                    .url(serverUrl)
                    .post(requestBody)
                    .build()

                val response = client.newCall(request).execute()
                if (response.isSuccessful) {
                    Result.success(response.body?.string() ?: "OK")
                } else {
                    Result.failure(Exception("Код ошибки сервера: ${response.code}"))
                }
            } catch (e: Exception) {
                Result.failure(e)
            }
        }
    }
}
